print(42 > 12)                  # True: 42 is greater than 12
# print(12 = 12)                -> SyntaxError: = is assignment, not comparison
print(12 == 12)                 # True: both values are equal
print("hello" == "world")       # False: the strings are different
print(218 >= 118)               # True: 218 is greater than 118
print("a".upper() == "A")       # True: "a".upper() becomes "A"
print(1 * 2 * 3 * 4 <= 9)       # False: 1*2*3*4 = 24, and 24 is not <= 9
print("z" in "azerty")          # True: "azerty" contains the letter z
